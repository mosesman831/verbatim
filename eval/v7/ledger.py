def render_ledger(idx: SpecIndex, registry: dict, disp: Dispositions) -> dict:
    """The machine-readable ledger_v7.json document."""
    reqs = {}
    for rid, r in registry.items():
        reqs[rid] = {
            "section": f"V7-{r['section']:02d}",
            "spec_section": r["spec_section"],
            "subsection": (
                f"{r['spec_section']:02d}.{r['subsection']}"
                if r["subsection"] >= 0 else ""
            ),
            "section_title": r["section_title"],
            "spec": r["spec"],
            "spec_line": r["line"],
            "capability": r["capability"],
            "profile": r["profile"],
            "owner": r["owner"],
            "stage": r["stage"],
            "stage_source": r["stage_source"],
            "code_surfaces": r["code_surfaces"],
            "scenarios": r["scenarios"],
            "spec_scenarios": r["spec_scenarios"],
            "scoreboard": r["scoreboard"],
            "gate": r["gate"],
            "envelopes": r["envelopes"],
            "defects": r["defects"],
            "inherited_requirements": r["inherited_requirements"],
            "inherited_gates": r["inherited_gates"],
            "inherited_scenarios": r["inherited_scenarios"],
            "inherited_envelopes": r["inherited_envelopes"],
            "evidence_type": r["evidence_type"],
            "executed_evidence": r["executed_evidence"],
            "implementation_status": r["implementation_status"],
            "qualification_status": r["qualification_status"],
            "status": r["status"],
            "blocker": r["blocker"],
            "note": r["note"],
            "text": r["text"],
        }
    summary_status = {s: 0 for s in STATUSES}
    summary_stage = {s: 0 for s in STAGES}
    summary_stage[""] = 0
    summary_impl = {s: 0 for s in IMPLEMENTATION_STATUSES}
    summary_qual = {s: 0 for s in QUALIFICATION_STATUSES}
    for r in registry.values():
        summary_status[r["status"]] += 1
        summary_stage[r["stage"]] += 1
        summary_impl[r["implementation_status"]] += 1
        summary_qual[r["qualification_status"]] += 1

    scenarios = {}
    for sc_id, sc in sorted(idx.scenarios.items()):
        scenarios[sc_id] = {
            "spec": sc.spec,
            "spec_line": sc.line,
            "text": sc.text,
            "envelopes": list(sc.envelopes),
            "bound_gates": sorted(
                g.gate_id for g in idx.gates.values()
                if sc_id in g.scenarios
            ),
            "status": "not_run",
            "anchored_requirements": sorted(
                rid for rid, r in registry.items()
                if sc_id in r["scenarios"]
            ),
        }
    gates = {}
    for gid, g in sorted(idx.gates.items()):
        gates[gid] = {
            "spec": g.spec,
            "spec_line": g.line,
            "name": g.name,
            "permits": g.permits,
            "requires": g.requires,
            "requirements": list(g.requirements),
            "scoreboard": list(g.scoreboard),
            "scenarios": list(g.scenarios),
            "envelopes": list(g.envelopes),
            "status": "not_run",
            "bound_requirements": sorted(
                rid for rid, r in registry.items() if gid in r["gate"]
            ),
        }
    scoreboard = {}
    for sid, sb in sorted(idx.scoreboard.items()):
        scoreboard[sid] = {
            "spec": sb.spec,
            "spec_line": sb.line,
            "benchmark": sb.benchmark,
            "metric": sb.metric,
            "target": sb.target,
            "reference": sb.reference,
            "status": "not_run",
            "bound_gates": sorted(
                g.gate_id for g in idx.gates.values()
                if sid in g.scoreboard
            ),
            "anchored_requirements": sorted(
                rid for rid, r in registry.items()
                if sid in r["scoreboard"]
            ),
        }
    envelopes = {}
    for eid, e in sorted(idx.envelopes.items()):
        envelopes[eid] = {
            "spec": e.spec,
            "spec_line": e.line,
            "workload": e.workload,
            "targets": e.targets,
            "status": "not_run",
            "bound_gates": sorted(
                g.gate_id for g in idx.gates.values()
                if eid in g.envelopes
            ),
            "anchored_requirements": sorted(
                rid for rid, r in registry.items()
                if eid in r["envelopes"]
            ),
        }
    defects = {}
    for did, d in sorted(idx.defects.items()):
        defects[did] = {
            "spec": d.spec,
            "spec_line": d.line,
            "defect": d.defect,
            "location": d.location,
            "consequence": d.consequence,
            "closed_by": list(d.closed_by),
            "trace_scenarios": list(
                idx.traces[did].scenarios) if did in idx.traces else [],
            "status": "open",
        }
    traces = {}
    for did, t in sorted(idx.traces.items()):
        traces[did] = {
            "spec": t.spec,
            "spec_line": t.line,
            "label": t.label,
            "requirements": list(t.requirements),
            "scenarios": list(t.scenarios),
        }
    stages = {}
    for sid, st in sorted(idx.stages.items()):
        stages[sid] = {
            "spec": st.spec,
            "spec_line": st.line,
            "main_work": st.main_work,
            "exit": st.exit_text,
            "exit_gates": list(st.exit_gates),
            "exit_scenarios": list(st.exit_scenarios),
            "exit_scoreboard": list(st.exit_scoreboard),
            "exit_envelopes": list(st.exit_envelopes),
        }
    return {
        "schema": 1,
        "generated_by": "eval/v7/ledger.py",
        "specs": {SPEC_FILE: {"sha256": idx.spec_sha256.get(SPEC_FILE, "")}},
        "statuses": list(STATUSES),
        "implementation_statuses": list(IMPLEMENTATION_STATUSES),
        "qualification_statuses": list(QUALIFICATION_STATUSES),
        "evidence_labels": list(EVIDENCE_LABELS),
        "stages": list(STAGES),
        "registries": {
            "scenarios": f"H{SCENARIO_RANGE[0]:02d}–H{SCENARIO_RANGE[1]}",
            "gates": f"G7-{GATE_RANGE[0]:02d}–G7-{GATE_RANGE[1]:02d}",
            "scoreboard": f"SB-{SCOREBOARD_RANGE[0]:02d}–SB-{SCOREBOARD_RANGE[1]:02d}",
            "envelopes": f"B{ENVELOPE_RANGE[0]}–B{ENVELOPE_RANGE[1]}",
            "defects": f"D7-{DEFECT_RANGE[0]:02d}–D7-{DEFECT_RANGE[1]:02d}",
        },
        "summary": {
            "total": len(registry),
            "by_status": summary_status,
            "by_implementation_status": summary_impl,
            "by_qualification_status": summary_qual,
            "by_stage": {k: v for k, v in summary_stage.items()},
            "requirements_with_scenarios": sum(
                1 for r in registry.values() if r["scenarios"]
            ),
            "requirements_with_gates": sum(
                1 for r in registry.values() if r["gate"]
            ),
            "requirements_with_scoreboard": sum(
                1 for r in registry.values() if r["scoreboard"]
            ),
            "disposition_overrides": len(disp.entries),
            "dispositions_missing": disp.missing,
            "scenarios_total": len(idx.scenarios),
            "gates_total": len(idx.gates),
            "scoreboard_total": len(idx.scoreboard),
            "envelopes_total": len(idx.envelopes),
            "defects_total": len(idx.defects),
            "traces_total": len(idx.traces),
        },
        "requirements": reqs,
        "scenarios": scenarios,
        "gates": gates,
        "scoreboard": scoreboard,
        "envelopes": envelopes,
        "defects": defects,
        "traces": traces,
        "stages_defined": stages,
    }


def render_ledger_text(idx: SpecIndex, registry: dict,
                       disp: Dispositions) -> str:
    """Canonical ledger JSON bytes (indent=2, sorted keys — same
    convention as the v6 artifact so freshness checks are byte-exact)."""
    return json.dumps(
        render_ledger(idx, registry, disp),
        indent=2, sort_keys=True, ensure_ascii=False,
    ) + "\n"


