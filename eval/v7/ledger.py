def _sort_sc_ids(ids) -> list:
    """Numeric-within-letter sort: H99 precedes H100; inherited
    E/C/D/F ids sort by letter then number."""
    return sorted(ids, key=lambda s: (s[0], int(s[1:])))


def defect_scenarios(idx: SpecIndex) -> dict:
    """defect id -> scenario ids from Appendix B trace rows."""
    return {d: list(t.scenarios) for d, t in idx.traces.items()}


def defect_requirements(idx: SpecIndex) -> dict:
    """defect id -> requirement ids that close it: Appendix B trace
    cells plus the §02.2 register's closed-by cell."""
    out: dict = {}
    for d, t in idx.traces.items():
        out.setdefault(d, set()).update(t.requirements)
    for d, df in idx.defects.items():
        out.setdefault(d, set()).update(df.closed_by)
    return {d: sorted(v) for d, v in out.items()}


def infer_requirement_stage(idx: SpecIndex, req: RequirementDef) -> tuple:
    """(stage, source) for one requirement.

    An explicit `PN MUST` directive or a "formula search" mention in
    the requirement text wins; otherwise the ``(section, subsection)``
    fallback applies, with a second lookup on ``(id_section, -1)`` for
    the §25-located ids that belong to other sections. `""` means no
    phase is inferable — provenance is recorded either way.
    """
    m = _STAGE_DIRECTIVE_RE.search(req.text)
    if m:
        return f"P{m.group(1)}", "text"
    if _FORMULA_SEARCH_RE.search(req.text):
        return "P2b", "text"
    key = (req.section, req.subsection)
    if key in SECTION_STAGE_FALLBACK:
        return SECTION_STAGE_FALLBACK[key], "fallback"
    key = (req.section, -1)
    if key in SECTION_STAGE_FALLBACK:
        return SECTION_STAGE_FALLBACK[key], "fallback"
    if req.id_section != req.section:
        return SECTION_STAGE_FALLBACK.get((req.id_section, -1), ""), "fallback"
    return SECTION_STAGE_FALLBACK.get((req.id_section, -1), ""), "fallback"


def infer_requirement_scenarios(idx: SpecIndex, req: RequirementDef) -> list:
    """H-scenarios a requirement anchors.

    Two spec-declared channels: H-ids the requirement text names
    (ranges excluded — a range declares the registry), and Appendix B
    trace scenarios for every defect the requirement is bound to
    (through its own `D7-NN` mentions, the register's closed-by cell,
    or the trace row's requirement cell).
    """
    out = set(_h_mentions(req.text))
    d2s = defect_scenarios(idx)
    d2r = defect_requirements(idx)
    own = set(_defect_mentions(req.text))
    for d in own:
        out.update(d2s.get(d) or ())
    for d, reqs in d2r.items():
        if req.req_id in reqs:
            out.update(d2s.get(d) or ())
    return _sort_sc_ids(out)


def infer_requirement_gates(idx: SpecIndex, req: RequirementDef,
                            scoreboard: Optional[list] = None) -> list:
    """G7 gates a requirement binds: explicit `G7-NN` text mentions
    (ranges excluded), gates whose Permits/Requires cells name the
    requirement id, and gates sharing a scoreboard row or envelope
    token with the requirement."""
    out = set(_gate_mentions(req.text))
    env = set(envelopes_in(req.text))
    sbs = set(_sb_mentions(req.text))
    if scoreboard:
        sbs |= set(scoreboard)
    for g in idx.gates.values():
        if req.req_id in g.requirements:
            out.add(g.gate_id)
            continue
        if sbs and set(g.scoreboard) & sbs:
            out.add(g.gate_id)
            continue
        if env and set(g.envelopes) & env:
            out.add(g.gate_id)
    return sorted(out)


def infer_requirement_defects(idx: SpecIndex, req: RequirementDef) -> list:
    """D7 defects a requirement is bound to: `D7-NN` mentions in its
    own text, register closed-by cells, and Appendix B trace cells."""
    out = set(_defect_mentions(req.text))
    for d, reqs in defect_requirements(idx).items():
        if req.req_id in reqs:
            out.add(d)
    return sorted(out)


def capability_for(req: RequirementDef) -> str:
    """One capability label per *id* section (the id namespace owns the
    semantic bucket — a §25-located V7-12.15 is a packs requirement).
    Unknown sections fall back to a slug of the section title."""
    if req.id_section in SECTION_CAPABILITY:
        return SECTION_CAPABILITY[req.id_section]
    slug = re.sub(r"[^a-z0-9]+", "-", req.section_title.lower()).strip("-")
    return slug or "unsectioned"


def rollup_status(impl: str, qual: str) -> str:
    """Derived ``status`` — never set directly (V7-00.06)."""
    if qual == "failed":
        return "failed"
    if qual == "not_applicable" or impl == "not_applicable":
        return "not_applicable"
    if qual == "qualified":
        return "qualified"
    if qual == "locally_measured":
        return "locally_measured"
    if impl == "implemented":
        return "implemented_unmeasured"
    if impl == "in_progress":
        return "in_progress"
    return "planned"


