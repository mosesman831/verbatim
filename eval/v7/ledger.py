@dataclass
class SpecIndex:
    """Merged parse of SPEC_V7.md (+ inherited id sets, read-only)."""

    requirements: dict = field(default_factory=dict)   # id -> RequirementDef
    scenarios: dict = field(default_factory=dict)      # H-id -> ScenarioDef
    gates: dict = field(default_factory=dict)          # G7-id -> GateDef
    scoreboard: dict = field(default_factory=dict)     # SB-id -> ScoreboardDef
    envelopes: dict = field(default_factory=dict)      # B-id -> EnvelopeDef
    defects: dict = field(default_factory=dict)        # D7-id -> DefectDef
    traces: dict = field(default_factory=dict)         # D7-id -> TraceDef
    stages: dict = field(default_factory=dict)         # P-id -> StageDef
    section_titles: dict = field(default_factory=dict)  # int -> title
    references: dict = field(default_factory=dict)     # id -> [spec:line]
    duplicates: list = field(default_factory=list)     # [str]
    spec_sha256: dict = field(default_factory=dict)    # file -> hex
    inherited_scenarios: set = field(default_factory=set)  # E/C/D/F ids
    inherited_gates: set = field(default_factory=set)      # G4/G5/G6 ids

    def scenario_envelopes(self, sc_id: str) -> tuple:
        sc = self.scenarios.get(sc_id)
        return sc.envelopes if sc else ()


def _record_refs(idx: SpecIndex, text: str, where: str,
                 skip_req: Optional[str] = None) -> None:
    """Register every V7 id ``text`` mentions (for undefined-ref checks).

    V2–V6 identifiers (``V6-02.13``, ``G6-00``, ``E02``, ``F4-11``) are
    inherited namespaces — recorded per row via :func:`_inherited_mentions`,
    never as references to satisfy here. ``D7-NN`` ids are recorded too:
    the D7-01..D7-40 namespace is declared by V7-00.03 even where the
    register has no row yet.
    """
    for rid in anchors_in(text):
        if rid != skip_req:
            idx.references.setdefault(rid, []).append(where)
    for sc in hids_in(text):
        idx.references.setdefault(sc, []).append(where)
    for g in gates_in(text):
        idx.references.setdefault(g, []).append(where)
    for sb in scoreboard_in(text):
        idx.references.setdefault(sb, []).append(where)
    for env in envelopes_in(text):
        idx.references.setdefault(env, []).append(where)
    for d in _defect_mentions(text):
        idx.references.setdefault(d, []).append(where)


def _parse_spec_text(raw: str, fname: str, idx: SpecIndex) -> None:
    """Parse one spec's text into ``idx`` (testable without files)."""
    idx.spec_sha256[fname] = hashlib.sha256(raw.encode("utf-8")).hexdigest()

    section = -1
    subsection = -1
    section_title = ""
    in_fence = False
    for n, line in enumerate(raw.splitlines(), 1):
        if _FENCE_RE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            # example packs / prompts may quote ids; they never define
            _record_refs(idx, line, f"{fname}:{n}")
            continue
        m = _SECTION_RE.match(line)
        if m:
            section = int(m.group(1))
            subsection = -1
            section_title = m.group(2).strip()
            idx.section_titles[section] = section_title
            _record_refs(idx, line, f"{fname}:{n}")
            continue
        sm = _SUBSECTION_RE.match(line)
        if sm and int(sm.group(1)) == section:
            subsection = int(sm.group(2))
            _record_refs(idx, line, f"{fname}:{n}")
            continue
        m = _DEF_RE.match(line)
        if m:
            rid = f"V7-{m.group(1)}.{m.group(2)}"
            where = f"{fname}:{n}"
            if rid in idx.requirements:
                prev = idx.requirements[rid]
                idx.duplicates.append(
                    f"{rid} defined twice: {prev.spec}:{prev.line} "
                    f"and {where}"
                )
                continue
            idx.requirements[rid] = RequirementDef(
                req_id=rid,
                spec=fname,
                section=section,
                subsection=subsection,
                id_section=int(m.group(1)),
                id_subsection=int(m.group(2)),
                section_title=section_title,
                text=m.group(3).strip(),
                line=n,
            )
            _record_refs(idx, m.group(3), where, skip_req=rid)
            continue
        sm = _SCENARIO_ROW_RE.match(line)
        if sm:
            sc_id, rest = sm.group(1), sm.group(2)
            cells = [c.strip() for c in rest.split("|")]
            desc = cells[0] if cells else ""
            where = f"{fname}:{n}"
            if sc_id in idx.scenarios:
                prev = idx.scenarios[sc_id]
                idx.duplicates.append(
                    f"scenario {sc_id} defined twice: "
                    f"{prev.spec}:{prev.line} and {where}"
                )
            else:
                idx.scenarios[sc_id] = ScenarioDef(
                    sc_id=sc_id, spec=fname, text=desc,
                    envelopes=tuple(envelopes_in(desc)), line=n,
                )
            _record_refs(idx, rest, where)
            continue
        gm = _GATE_ROW_RE.match(line)
        if gm:
            gate_id, name, rest = gm.group(1), gm.group(2).strip(), gm.group(3)
            cells = [c.strip() for c in rest.split("|")]
            permits = cells[0] if len(cells) > 0 else ""
            requires = cells[1] if len(cells) > 1 else ""
            where = f"{fname}:{n}"
            if gate_id in idx.gates:
                prev = idx.gates[gate_id]
                idx.duplicates.append(
                    f"gate {gate_id} defined twice: "
                    f"{prev.spec}:{prev.line} and {where}"
                )
            else:
                idx.gates[gate_id] = GateDef(
                    gate_id=gate_id, spec=fname, name=name,
                    permits=permits, requires=requires,
                    requirements=tuple(anchors_in(rest)),
                    scoreboard=tuple(scoreboard_in(rest)),
                    scenarios=tuple(hids_in(rest)),
                    envelopes=tuple(envelopes_in(rest)),
                    sections=tuple(sections_in(rest)),
                    line=n,
                )
            _record_refs(idx, rest, where)
            continue
        bm = _SCOREBOARD_ROW_RE.match(line)
        if bm:
            sb_id, rest = bm.group(1), bm.group(2)
            cells = [c.strip() for c in rest.split("|")]
            where = f"{fname}:{n}"
            if sb_id in idx.scoreboard:
                prev = idx.scoreboard[sb_id]
                idx.duplicates.append(
                    f"scoreboard {sb_id} defined twice: "
                    f"{prev.spec}:{prev.line} and {where}"
                )
            else:
                idx.scoreboard[sb_id] = ScoreboardDef(
                    sb_id=sb_id, spec=fname,
                    benchmark=cells[0] if len(cells) > 0 else "",
                    metric=cells[1] if len(cells) > 1 else "",
                    target=cells[2] if len(cells) > 2 else "",
                    reference=cells[3] if len(cells) > 3 else "",
                    line=n,
                )
            _record_refs(idx, rest, where)
            continue
        em = _ENVELOPE_ROW_RE.match(line)
        if em:
            env_id, rest = em.group(1), em.group(2)
            cells = [c.strip() for c in rest.split("|")]
            where = f"{fname}:{n}"
            if env_id in idx.envelopes:
                prev = idx.envelopes[env_id]
                idx.duplicates.append(
                    f"envelope {env_id} defined twice: "
                    f"{prev.spec}:{prev.line} and {where}"
                )
            else:
                idx.envelopes[env_id] = EnvelopeDef(
                    env_id=env_id, spec=fname,
                    workload=cells[0] if len(cells) > 0 else "",
                    targets=cells[1] if len(cells) > 1 else "",
                    line=n,
                )
            _record_refs(idx, rest, where)
            continue
        tm = _TRACE_ROW_RE.match(line)
        if tm:
            defect_id, label, rest = tm.group(1), tm.group(2), tm.group(3)
            cells = [c.strip() for c in rest.split("|")]
            reqs_cell = cells[0] if len(cells) > 0 else ""
            sc_cell = cells[1] if len(cells) > 1 else ""
            where = f"{fname}:{n}"
            if defect_id in idx.traces:
                prev = idx.traces[defect_id]
                idx.duplicates.append(
                    f"trace {defect_id} defined twice: "
                    f"{prev.spec}:{prev.line} and {where}"
                )
            else:
                idx.traces[defect_id] = TraceDef(
                    defect_id=defect_id, spec=fname, label=label,
                    requirements=tuple(anchors_in(reqs_cell)),
                    scenarios=tuple(hids_in(sc_cell)),
                    line=n,
                )
            _record_refs(idx, rest, where)
            continue
        dm = _DEFECT_ROW_RE.match(line)
        if dm:
            defect_id, rest = dm.group(1), dm.group(2)
            cells = [c.strip() for c in rest.split("|")]
            where = f"{fname}:{n}"
            if defect_id in idx.defects:
                prev = idx.defects[defect_id]
                idx.duplicates.append(
                    f"defect {defect_id} defined twice: "
                    f"{prev.spec}:{prev.line} and {where}"
                )
            else:
                idx.defects[defect_id] = DefectDef(
                    defect_id=defect_id, spec=fname,
                    defect=cells[0] if len(cells) > 0 else "",
                    location=cells[1] if len(cells) > 1 else "",
                    consequence=cells[2] if len(cells) > 2 else "",
                    closed_by=tuple(anchors_in(
                        cells[3] if len(cells) > 3 else "")),
                    line=n,
                )
            _record_refs(idx, rest, where)
            continue
        pm = _STAGE_ROW_RE.match(line)
        if pm:
            stage_id, rest = pm.group(1), pm.group(2)
            cells = [c.strip() for c in rest.split("|")]
            work = cells[0] if len(cells) > 0 else ""
            exit_text = cells[1] if len(cells) > 1 else ""
            where = f"{fname}:{n}"
            if stage_id in idx.stages:
                prev = idx.stages[stage_id]
                idx.duplicates.append(
                    f"stage {stage_id} defined twice: "
                    f"{prev.spec}:{prev.line} and {where}"
                )
            else:
                idx.stages[stage_id] = StageDef(
                    stage_id=stage_id, spec=fname,
                    main_work=work, exit_text=exit_text,
                    exit_gates=tuple(gates_in(exit_text)),
                    exit_scenarios=tuple(hids_in(exit_text)),
                    exit_scoreboard=tuple(scoreboard_in(exit_text)),
                    exit_envelopes=tuple(envelopes_in(exit_text)),
                    line=n,
                )
            _record_refs(idx, rest, where)
            continue
        _record_refs(idx, line, f"{fname}:{n}")


def _scan_inherited(raw: str) -> tuple:
    """(scenario ids, gate ids) an inherited spec defines."""
    scenarios = {m.group(1) for m in _INH_SCENARIO_ROW_RE.finditer(raw)}
    gates = {m.group(1) for m in _INH_GATE_ROW_RE.finditer(raw)}
    return scenarios, gates


def load_specs(root: str, spec_file: str = SPEC_FILE) -> SpecIndex:
    """Parse SPEC_V7.md; also collect inherited id sets (read-only)."""
    idx = SpecIndex()
    path = os.path.join(root, spec_file)
    try:
        with open(path, "r", encoding="utf-8") as f:
            raw = f.read()
    except OSError as e:
        raise LedgerError(f"cannot read {path}: {e}")
    _parse_spec_text(raw, spec_file, idx)
    for fname in INHERITED_SPEC_FILES:
        ipath = os.path.join(root, fname)
        try:
            with open(ipath, "r", encoding="utf-8") as f:
                sc, gates = _scan_inherited(f.read())
                idx.inherited_scenarios |= sc
                idx.inherited_gates |= gates
        except OSError:
            continue  # inherited specs absent: their validation is skipped
    return idx


