def _read(path: str) -> str:
    try:
        with open(path, "r", encoding="utf-8") as f:
            return f.read()
    except OSError:
        return ""


def _write(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def _pipeline(root: str):
    """Shared front half for both modes: parse spec + dispositions."""
    try:
        idx = load_specs(root)
    except LedgerError as e:
        print(f"error: {e}", file=sys.stderr)
        return None
    disp_path = os.path.join(root, DEFAULT_DISPOSITIONS_PATH)
    if os.path.exists(disp_path):
        try:
            disp = load_dispositions(disp_path)
        except LedgerError as e:
            print(f"error: {e}", file=sys.stderr)
            return None
    else:
        disp = Dispositions(source_path=disp_path, missing=True)
    return idx, disp


def cmd_check(root: str) -> int:
    pipe = _pipeline(root)
    if pipe is None:
        return 2
    idx, disp = pipe
    issues = validate(idx, disp, root=root)

    # the generated artifact must parse and be byte-identical to a
    # regeneration — that is what "all spec ids present" means
    json_path = os.path.join(root, DEFAULT_JSON_PATH)
    raw = _read(json_path)
    if not raw:
        issues.append(f"{DEFAULT_JSON_PATH} is missing — run --write")
    else:
        try:
            doc = json.loads(raw)
        except json.JSONDecodeError as e:
            issues.append(f"{DEFAULT_JSON_PATH} does not parse: {e}")
        else:
            for key in ("requirements", "scenarios", "gates",
                        "scoreboard"):
                if key not in doc:
                    issues.append(
                        f"{DEFAULT_JSON_PATH} lacks collection {key!r}")
    registry = build_registry(idx, disp)
    ledger_json = render_ledger_text(idx, registry, disp)
    if raw and raw != ledger_json:
        issues.append(f"{DEFAULT_JSON_PATH} is stale — run --write")

    if issues:
        print(f"v7 ledger check FAILED ({len(issues)} issue(s)):")
        for i in issues:
            print(f"  - {i}")
        return 1
    summary = render_ledger(idx, registry, disp)["summary"]
    print(
        "v7 ledger OK: {total} requirements "
        "(qualified={q} locally_measured={m} implemented_unmeasured={u} "
        "in_progress={p} planned={pl} failed={f} not_applicable={n}); "
        "{sc} scenarios, {gates} gates, {sb} scoreboard rows, "
        "{env} envelopes, {df} defects".format(
            total=summary["total"],
            q=summary["by_status"]["qualified"],
            m=summary["by_status"]["locally_measured"],
            u=summary["by_status"]["implemented_unmeasured"],
            p=summary["by_status"]["in_progress"],
            pl=summary["by_status"]["planned"],
            f=summary["by_status"]["failed"],
            n=summary["by_status"]["not_applicable"],
            sc=summary["scenarios_total"],
            gates=summary["gates_total"],
            sb=summary["scoreboard_total"],
            env=summary["envelopes_total"],
            df=summary["defects_total"],
        )
    )
    return 0


def cmd_write(root: str) -> int:
    pipe = _pipeline(root)
    if pipe is None:
        return 2
    idx, disp = pipe

    registry = build_registry(idx, disp)
    ledger_json = render_ledger_text(idx, registry, disp)
    _write(os.path.join(root, DEFAULT_JSON_PATH), ledger_json)

    # the overlay, when present, is human-curated and preserved
    # verbatim; only the spec-hash pin is refreshed
    disp_path = os.path.join(root, DEFAULT_DISPOSITIONS_PATH)
    if not disp.missing:
        disp.spec_sha256 = dict(idx.spec_sha256)
        _write(disp_path, render_dispositions(disp))
        disp2 = load_dispositions(disp_path)
    else:
        disp2 = disp
    issues = validate(idx, disp2, root=root)
    print(
        f"wrote {DEFAULT_JSON_PATH} "
        f"({len(registry)} requirements, {len(idx.scenarios)} "
        f"scenarios, {len(idx.gates)} gates, {len(idx.scoreboard)} "
        f"scoreboard rows, {len(idx.envelopes)} envelopes, "
        f"{len(idx.defects)} defects; dispositions "
        f"{'absent' if disp.missing else str(len(disp2.entries)) + ' rows'})"
    )
    if issues:
        print(f"post-write validation FAILED ({len(issues)} issue(s)):")
        for i in issues:
            print(f"  - {i}")
        return 1
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="python -m eval.v7.ledger",
        description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="validate the parse + generated ledger (default)")
    ap.add_argument("--write", action="store_true",
                    help="regenerate eval/v7/ledger_v7.json")
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))),
        help="repo root (default: auto)")
    args = ap.parse_args(argv)
    if args.write:
        return cmd_write(args.root)
    return cmd_check(args.root)


if __name__ == "__main__":
    sys.exit(main())
