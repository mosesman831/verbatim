#: `- V7-NN.MM: text` — definition lines only.
_DEF_RE = re.compile(r"^-\s+V7-(\d{2})\.(\d{2}):\s*(.*)$")
#: `## NN. Title` top-level sections (`###` subsections do not match).
_SECTION_RE = re.compile(r"^##\s+(\d+)\.\s+(.+)$")
#: `### NN.M Title` — tracked so §13.1/§22.2-style programs bind their
#: own phases; the subsection number resets at every `##` heading.
_SUBSECTION_RE = re.compile(r"^###\s+(\d+)\.(\d+)\s*[.:—-]?\s*(.*)$")
#: Fenced code blocks — rows/definitions inside them never register.
_FENCE_RE = re.compile(r"^\s*```")
#: Any `V7-NN.MM` mention including `/MM`, `/NN.MM`, `–MM`, and
#: `–NN.MM` continuations (`V7-05.10/11`, `V7-05.01–09`).
_ANCHOR_RE = re.compile(r"\bV7-(\d{2})\.(\d{2})((?:[/–]\d{2}(?:\.\d{2})?)*)")
_ANCHOR_PART_RE = re.compile(r"([/–])(\d{2})(?:\.(\d{2}))?")
#: `| H01 | desc |` scenario rows (§28 — two cells).
_SCENARIO_ROW_RE = re.compile(r"^\|\s*(H\d{2,3})\s*\|(.*)\|\s*$")
#: `| G7-00 Authority | permits | requires |` gate rows (§26).
_GATE_ROW_RE = re.compile(r"^\|\s*(G7-\d{2})\s*([^|]*)\|(.*)\|\s*$")
#: `| SB-01 | benchmark | metric | target | reference |` (§03.2).
_SCOREBOARD_ROW_RE = re.compile(r"^\|\s*(SB-\d{2})\s*\|(.*)\|\s*$")
#: `| B0 | workload | targets |` envelope rows (§17.1; variants like
#: `B1-cache`/`B1-neural`/`B1-CE` are first-class ids).
_ENVELOPE_ROW_RE = re.compile(
    r"^\|\s*(B\d{1,2}(?:-(?:cache|neural|CE))?)\s*\|(.*)\|\s*$")
#: `| P0 | content | exit |` phase rows (§27.1 — P0..P10 plus P2b).
_STAGE_ROW_RE = re.compile(r"^\|\s*(P\d{1,2}b?)\s*\|(.*)\|\s*$")
#: `| D7-01 | defect | location | consequence | closed-by |` — §02.2
#: register rows have a *bare* id in the first cell.
_DEFECT_ROW_RE = re.compile(r"^\|\s*(D7-\d{2})\s*\|(.*)\|\s*$")
#: `| D7-01 name | reqs | scenarios |` — Appendix B trace rows carry
#: the id plus a label in the first cell (never a bare id).
_TRACE_ROW_RE = re.compile(
    r"^\|\s*(D7-\d{2})\s+([^\s|][^|]*?)\s*\|(.*)\|\s*$")
#: `§NN`, `§NN.MM`, `§NN–§MM`, `§NN.MM–MM.MM` (en dash).
_SECTION_REF_RE = re.compile(
    r"§(\d{2})(?:\.(\d{2}))?(?:\s*–\s*§?(\d{2})(?:\.(\d{2}))?)?"
)
#: Bare scenario ids and `HNN–HMM` ranges (backticks tolerated).
_HID_RE = re.compile(r"\bH(\d{2,3})\b")
_HRANGE_RE = re.compile(r"\bH(\d{2,3})`?\s*[–—]\s*`?H(\d{2,3})")
#: `G7-NN` incl. `/NN` continuations and `–`/`…`/`...` ranges
#: (`G7-00`–`G7-14` denotes the whole registry).
_GATE_REF_RE = re.compile(r"\bG7-(\d{2})((?:/\d{2})*)")
_GATE_RANGE_RE = re.compile(
    r"\bG7-(\d{2})`?\s*(?:–|—|\.\.\.|…)\s*`?G7-(\d{2})")
#: `SB-NN` incl. `/NN` continuations (`SB-01/02/03`).
_SB_REF_RE = re.compile(r"\bSB-(\d{2})((?:/\d{2})*)")
#: `D7-NN` defect mentions.
_DEFECT_REF_RE = re.compile(r"\bD7-(\d{2})")
#: Envelope tokens (`B1-CE` never double-counts as `B1`), and
#: `B0–B6`-style ranges.
_ENVELOPE_RE = re.compile(r"\bB(\d{1,2})(?:-(cache|neural|CE))?\b")
_ENVELOPE_RANGE_RE = re.compile(r"\bB(\d{1,2})`?\s*–\s*`?B(\d{1,2})\b")
#: Explicit phase directives inside requirement text (`P2 MUST …`,
#: `the formula search …` → the P2b phase).
_STAGE_DIRECTIVE_RE = re.compile(r"\bP(\d{1,2}b?)(?=\s+MUST)")
_FORMULA_SEARCH_RE = re.compile(r"\bformula[- ]search\b", re.I)
#: Profile names the spec registers (longest first so
#: `local_memory_max` never degrades to `local_memory`).
_PROFILE_RE = re.compile(
    r"\b(local_memory_max|local_memory_quality|local_memory"
    r"|local_rules|embedded)\b")
#: Inherited ids — recorded per row for context, never satisfied here:
#: `V6-02.13`, `V5-21.06`, `V4-28.03`, `V5-11`, `G6-00`, `E02`,
#: `F4-11`, and V6 A-envelope names (`A0`, `A0-cache`, `A0-neural`,
#: `A1`, `A3`) are all inherited namespaces.
_INHERITED_REQ_RE = re.compile(r"\bV[2-6]-\d{2}(?:\.\d{2})?\b")
_INHERITED_GATE_RE = re.compile(r"\bG([456])-(\d{2})((?:/\d{2})*)")
_INHERITED_SC_RE = re.compile(r"\b([ECD])(\d{2})\b|\bF4-(\d{2})\b")
_INHERITED_ENV_RE = re.compile(r"\bA0(?:-cache|-neural)?\b|\bA1\b|\bA3\b")
#: `| E01 |`/… scenario rows and `| G4/G5/G6-NN |` gate rows in the
#: inherited specs (overlay validation only).
_INH_SCENARIO_ROW_RE = re.compile(r"^\|\s*([ECDF]\d{2})\s*\|", re.M)
_INH_GATE_ROW_RE = re.compile(r"^\|\s*(G[456]-\d{2})\s", re.M)


def _expand_anchor(m: re.Match) -> list:
    """Expand one V7 anchor match into every id it denotes.

    `V7-04.02/03` -> [V7-04.02, V7-04.03]; `V7-05.01–09` expands the
    range V7-05.01..V7-05.09; `/NN.MM` and `–NN.MM` carry their own
    section. A cross-section `–NN.MM` range emits its endpoint only
    (no such form occurs in the spec; the semantics are undefined).
    """
    sec, sub, tail = m.groups()
    cur_sec, cur_sub = int(sec), int(sub)
    ids = [f"V7-{sec}.{sub}"]
    for op, a, b in _ANCHOR_PART_RE.findall(tail or ""):
        if op == "/":
            # `/MM` keeps the section; `/NN.MM` carries its own
            tsec, tsub = (int(a), int(b)) if b else (cur_sec, int(a))
            ids.append(f"V7-{tsec:02d}.{tsub:02d}")
            cur_sec, cur_sub = tsec, tsub
            continue
        # en-dash range endpoint
        tsec, tsub = (int(a), int(b)) if b else (cur_sec, int(a))
        if tsec != cur_sec:
            ids.append(f"V7-{tsec:02d}.{tsub:02d}")  # endpoint only
            cur_sec, cur_sub = tsec, tsub
            continue
        if tsub > cur_sub:
            ids.extend(
                f"V7-{cur_sec:02d}.{n:02d}"
                for n in range(cur_sub + 1, tsub + 1)
            )
            cur_sub = tsub
        else:
            ids.append(f"V7-{tsec:02d}.{tsub:02d}")
            cur_sec, cur_sub = tsec, tsub
    return ids


def anchors_in(text: str) -> list:
    """All `V7-NN.MM` ids mentioned in ``text`` (shorthand expanded)."""
    out = []
    for m in _ANCHOR_RE.finditer(text):
        out.extend(_expand_anchor(m))
    return out


def _h_mentions(text: str) -> list:
    """`HNN` singles, excluding members of `HNN–HMM` ranges (a range
    declares the namespace span, not a per-scenario binding)."""
    spans = [m.span() for m in _HRANGE_RE.finditer(text)]
    out = set()
    for m in _HID_RE.finditer(text):
        if any(s <= m.start() < e for s, e in spans):
            continue
        out.add(f"H{m.group(1)}")
    return sorted(out, key=lambda s: int(s[1:]))


def hids_in(text: str) -> list:
    """All `HNN` ids denoted by ``text`` — singles plus en-dash ranges
    fully expanded (numeric order — H99 precedes H100)."""
    out = set(_h_mentions(text))
    for a, b in _HRANGE_RE.findall(text):
        out.update(f"H{n:02d}" for n in range(int(a), int(b) + 1))
    return sorted(out, key=lambda s: int(s[1:]))


def _gate_mentions(text: str) -> list:
    """`G7-NN` singles + `/NN` continuations, excluding range members."""
    spans = [m.span() for m in _GATE_RANGE_RE.finditer(text)]
    out = set()
    for m in _GATE_REF_RE.finditer(text):
        if any(s <= m.start() < e for s, e in spans):
            continue
        out.add(f"G7-{m.group(1)}")
        out.update(f"G7-{n}" for n in re.findall(r"/(\d{2})", m.group(2) or ""))
    return sorted(out)


def gates_in(text: str) -> list:
    """All `G7-NN` ids denoted by ``text`` — singles, continuations,
    and ranges (`G7-10 … G7-13`) fully expanded."""
    out = set(_gate_mentions(text))
    for a, b in _GATE_RANGE_RE.findall(text):
        out.update(f"G7-{n:02d}" for n in range(int(a), int(b) + 1))
    return sorted(out)


def _sb_mentions(text: str) -> list:
    """`SB-NN` singles + `/NN` continuations."""
    out = set()
    for m in _SB_REF_RE.finditer(text):
        out.add(f"SB-{m.group(1)}")
        out.update(f"SB-{n}" for n in re.findall(r"/(\d{2})", m.group(2) or ""))
    return sorted(out)


def scoreboard_in(text: str) -> list:
    """Scoreboard ids denoted by ``text`` (same as singles — the spec
    never ranges SB ids)."""
    return _sb_mentions(text)


def _defect_mentions(text: str) -> list:
    """`D7-NN` defect ids mentioned (register rows + open reserve)."""
    return sorted({f"D7-{n}" for n in _DEFECT_REF_RE.findall(text)})


def envelopes_in(text: str) -> list:
    """Envelope tokens in ``text`` — `B1-CE` never counts as `B1`;
    `B0–B6` ranges expand."""
    out = set()
    for n, suffix in _ENVELOPE_RE.findall(text):
        out.add(f"B{n}" + (f"-{suffix}" if suffix else ""))
    for a, b in _ENVELOPE_RANGE_RE.findall(text):
        out.update(f"B{n}" for n in range(int(a), int(b) + 1))
    return sorted(out)


def sections_in(text: str) -> list:
    """Top-level spec sections a `§` reference list denotes."""
    out = set()
    for m in _SECTION_REF_RE.finditer(text):
        a, sub_a, b, sub_b = m.groups()
        if b and not sub_a and not sub_b:
            out.update(range(int(a), int(b) + 1))
        else:
            out.add(int(a))
    return sorted(out)


def _stages_in(text: str) -> list:
    """Phase tokens in a cell: `P2/P3` -> both; `All` -> none."""
    return sorted(
        {f"P{d}" for d in re.findall(r"\bP(\d{1,2}b?)\b", text)},
        key=STAGES.index,
    )


def profiles_in(text: str) -> list:
    """Registered profile names a text mentions."""
    return sorted(set(_PROFILE_RE.findall(text)))


def _inherited_mentions(text: str) -> dict:
    """V2–V6 ids a text mentions — context only, never validated."""
    gates = set()
    for gen, num, tail in _INHERITED_GATE_RE.findall(text):
        gates.add(f"G{gen}-{num}")
        gates.update(f"G{gen}-{n}" for n in re.findall(r"/(\d{2})", tail or ""))
    scens = set()
    for letter, num, f4 in _INHERITED_SC_RE.findall(text):
        scens.add(f"{letter}{num}" if letter else f"F4-{f4}")
    return {
        "inherited_requirements": sorted(set(_INHERITED_REQ_RE.findall(text))),
        "inherited_gates": sorted(gates),
        "inherited_scenarios": sorted(scens),
        "inherited_envelopes": sorted(set(_INHERITED_ENV_RE.findall(text))),
    }


class LedgerError(Exception):
    """Raised for unparseable inputs; validation failures are reported
    as issue lists instead (see :func:`validate`)."""


