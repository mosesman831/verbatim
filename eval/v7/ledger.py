@dataclass
class Dispositions:
    """Parsed eval/v7/dispositions_v7.json (may be absent)."""

    spec_sha256: dict = field(default_factory=dict)
    entries: dict = field(default_factory=dict)   # req_id -> dict of overrides
    source_path: str = DEFAULT_DISPOSITIONS_PATH
    #: ``missing`` defaults True: a bare ``Dispositions()`` is an
    #: absent overlay, so hash-pin checks stay silent until a real
    #: file is parsed (which sets it False explicitly).
    missing: bool = True


def _no_dup_object(pairs):
    """object_pairs_hook rejecting duplicate JSON keys (V7-00.03)."""
    out = {}
    for k, v in pairs:
        if k in out:
            raise LedgerError(f"duplicate key {k!r} in dispositions file")
        out[k] = v
    return out


def load_dispositions_from_text(text: str, source: str = "<dispositions>") -> Dispositions:
    """Parse dispositions JSON from a string."""
    try:
        raw = json.loads(text, object_pairs_hook=_no_dup_object)
    except LedgerError:
        raise
    except json.JSONDecodeError as e:
        raise LedgerError(f"cannot parse {source}: {e}")
    raw = raw or {}
    if not isinstance(raw, dict):
        raise LedgerError(f"{source}: top level must be a JSON object")
    disp = Dispositions(source_path=source, missing=False)
    disp.spec_sha256 = {
        str(k): str(v) for k, v in (raw.get("spec_sha256") or {}).items()
    }
    reqs = raw.get("requirements") or {}
    if not isinstance(reqs, dict):
        raise LedgerError(f"{source}: 'requirements' must be an object")
    for rid, body in reqs.items():
        if not isinstance(body, dict):
            raise LedgerError(f"{source}: entry {rid} must be an object")
        disp.entries[rid] = dict(body)
    return disp


def load_dispositions(path: str) -> Dispositions:
    """Load the overlay if it exists; a missing file is honest absence
    (``missing=True``), not an error — the overlay is optional in V7."""
    disp_missing = Dispositions(source_path=path, missing=True)
    try:
        with open(path, "r", encoding="utf-8") as f:
            return load_dispositions_from_text(f.read(), path)
    except LedgerError:
        raise
    except OSError:
        return disp_missing


def render_dispositions(disp: Dispositions) -> str:
    """Canonical serialization — ``--write`` refreshes only the
    spec-hash pin; curated entries are preserved verbatim."""
    doc = {
        "schema": 1,
        "_doc": (
            "Curated overlay for the V7 requirements ledger "
            "(SPEC_V7 V7-00.06). Keys per requirement: owner, "
            "profile, stage, code_surfaces, scenarios (H ids plus "
            "inherited E/C/D ids), scoreboard (SB ids), gate (G7 "
            "ids; G4/G5/G6 inherited), evidence_type "
            "(DOC/CODE/LOCAL/BENCH/INDEPENDENT), executed_evidence "
            "(named executed checks/runs — required for "
            "locally_measured/qualified), implementation_status, "
            "qualification_status (incl. deferred — owner + reason "
            "mandatory), blocker, note. spec_sha256 is refreshed by "
            "`python -m eval.v7.ledger --write`."
        ),
        "spec_sha256": dict(sorted(disp.spec_sha256.items())),
        "requirements": {
            rid: disp.entries[rid] for rid in sorted(disp.entries)
        },
    }
    return json.dumps(doc, indent=2, sort_keys=True,
                      ensure_ascii=False) + "\n"


