"""Executable-traceability ledger for SPEC_V7 (V7-00.03/00.06, V7-26.02).

Same honesty question as the v6 ledger — which requirement has *named
executed evidence* behind it — under the same two-axis status model:
``implementation_status`` and ``qualification_status`` are separate
axes and the rollup ``status`` is derived, never set directly
(V6-00.06 carried into V7-00.06). Everything seeds
``planned``/``not_run``; ``locally_measured``/``qualified`` require
named executed evidence from the declared gate procedure — a spec
citation is never evidence.

Artifact layout (this module owns one generated file):

* ``eval/v7/ledger_v7.json`` — the single machine-readable ledger.
  Named collections inside it: ``requirements`` (every ``V7-NN.MM``
  definition, 349 rows at spec R1), ``scenarios`` (the §28 H01–H104
  acceptance rows — the registry is declared "H01–H104" in V7-00.03
  even though the §28 heading says H96; the table runs to H104),
  ``gates`` (§26 G7-00–G7-14 with both the Permits and Requires
  cells), ``scoreboard`` (§03.2 SB-01–SB-20), ``envelopes`` (§17.1
  B0–B6 plus the B1-cache/B1-neural/B1-CE variants),
  ``defects`` (§02.2 D7-01–D7-24 register rows; D7-25..D7-40 are
  reserved by V7-00.03 for the audit wave and are valid namespace
  references while undefined), ``traces`` (Appendix B
  defect → requirement → scenario rows), and ``stages_defined``
  (§27.1 P0–P10 plus P2b). No sidecar files.

CLI (``python -m eval.v7.ledger``):

* ``--check`` (default) — validate the parse and the generated
  artifact: no duplicate definitions, no references to undefined
  requirements/scenarios/gates/scoreboard rows/envelopes, no ids
  outside the declared registries, ``ledger_v7.json`` parses and is
  byte-identical to a regeneration (so every spec id is present), and
  the optional ``eval/v7/dispositions_v7.json`` overlay — if present —
  is schema-valid. Exits nonzero on any issue.
* ``--write`` — regenerate ``ledger_v7.json`` (and refresh the overlay
  spec-hash pin if the overlay exists), then re-validate.

Differences from the v6 grammar (deliberate, spec-driven):

* V7 uses en-dash subsection ranges as well as ``/MM`` shorthand:
  ``V7-05.01–09`` expands to V7-05.01..V7-05.09. ``/NN.MM`` and
  ``–NN.MM`` forms are also understood.
* Gate rows carry a third cell (``Requires``) which is preserved.
* Scenario ids are ``H01``–``H104`` (three digits allowed), gates are
  ``G7-NN`` with ``/NN`` continuations and ``–``/``…`` ranges
  (``G7-10 … G7-13``), scoreboard ids ``SB-NN`` carry ``/NN``
  continuations, envelopes are the ``B`` family, defects ``D7-NN``.
* Five requirements are defined inside §25 playbook text with ids
  owned by other sections (V7-12.15, V7-14.11, V7-14.12, V7-15.10,
  V7-21.17). V6 treated id≠section as a spec defect; V7 does it
  deliberately, so it is NOT an error — rows record the semantic
  ``section`` (from the id) and the physical ``spec_section`` where
  the definition lives, and capability/stage inference keys on the id.
* The overlay ``eval/v7/dispositions_v7.json`` is OPTIONAL and
  read-only here: it is never generated by this module (wave-A owns
  only the artifacts listed above). When absent the ledger is still
  complete; when present it must pin the live spec hash.
"""

