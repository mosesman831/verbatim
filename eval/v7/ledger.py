def _is_scenario_id(s: str) -> bool:
    return bool(re.match(r"^(H\d{2,3}|[ECDF]\d{2})$", s))


def _is_gate_id(s: str) -> bool:
    return bool(re.match(r"^G[4-7]-\d{2}$", s))


def _in_registry(num: int, span: tuple) -> bool:
    return span[0] <= num <= span[1]


def validate(idx: SpecIndex, disp: Dispositions, root: Optional[str] = None) -> list:
    """Return ledger violations; empty means the ledger is valid.

    ``root`` enables the code-surface existence check (a surface that
    disappears is a stale mapping).
    """
    issues: list = []

    for dup in idx.duplicates:
        issues.append(f"duplicate spec definition: {dup}")

    defined = set(idx.requirements)
    for rid, refs in sorted(idx.references.items()):
        if rid.startswith("H"):
            n = int(rid[1:])
            if not _in_registry(n, SCENARIO_RANGE):
                issues.append(
                    f"spec reference to scenario {rid} outside the "
                    f"declared H{SCENARIO_RANGE[0]:02d}–"
                    f"H{SCENARIO_RANGE[1]} registry ({refs[0]})"
                )
            elif rid not in idx.scenarios:
                issues.append(
                    f"spec reference to undefined scenario {rid} ({refs[0]})"
                )
            continue
        if rid.startswith("G7-"):
            n = int(rid.split("-")[1])
            if not _in_registry(n, GATE_RANGE):
                issues.append(
                    f"spec reference to gate {rid} outside the "
                    f"declared G7-{GATE_RANGE[0]:02d}–"
                    f"G7-{GATE_RANGE[1]:02d} registry ({refs[0]})"
                )
            elif rid not in idx.gates:
                issues.append(
                    f"spec reference to undefined gate {rid} ({refs[0]})"
                )
            continue
        if rid.startswith("SB-"):
            n = int(rid.split("-")[1])
            if not _in_registry(n, SCOREBOARD_RANGE):
                issues.append(
                    f"spec reference to scoreboard row {rid} outside "
                    f"the declared SB-{SCOREBOARD_RANGE[0]:02d}–"
                    f"SB-{SCOREBOARD_RANGE[1]:02d} registry ({refs[0]})"
                )
            elif rid not in idx.scoreboard:
                issues.append(
                    f"spec reference to undefined scoreboard row {rid} "
                    f"({refs[0]})"
                )
            continue
        if rid.startswith("D7-"):
            n = int(rid.split("-")[1])
            if not _in_registry(n, DEFECT_RANGE):
                issues.append(
                    f"spec reference to defect {rid} outside the "
                    f"declared D7-{DEFECT_RANGE[0]:02d}–"
                    f"D7-{DEFECT_RANGE[1]:02d} registry ({refs[0]})"
                )
            # D7-25..D7-40 are reserved for the audit wave (V7-00.03):
            # a reference to a reserved-but-undefined defect is legal.
            continue
        if rid.startswith("B"):
            n = int(rid[1])
            if not _in_registry(n, ENVELOPE_RANGE):
                issues.append(
                    f"spec reference to envelope {rid} outside the "
                    f"declared B{ENVELOPE_RANGE[0]}–"
                    f"B{ENVELOPE_RANGE[1]} registry ({refs[0]})"
                )
            elif rid not in idx.envelopes:
                issues.append(
                    f"spec reference to undefined envelope {rid} ({refs[0]})"
                )
            continue
        if rid not in defined:
            issues.append(
                f"spec reference to undefined requirement {rid} "
                f"({refs[0]}, +{len(refs) - 1} more)"
            )

    # declared registries — a defined row outside the span is a defect
    for sc in sorted(idx.scenarios.values(), key=lambda s: s.sc_id):
        n = int(sc.sc_id[1:])
        if not _in_registry(n, SCENARIO_RANGE):
            issues.append(
                f"scenario {sc.sc_id} outside the declared "
                f"H{SCENARIO_RANGE[0]:02d}–H{SCENARIO_RANGE[1]} "
                f"registry ({sc.spec}:{sc.line})"
            )
    for g in sorted(idx.gates.values(), key=lambda g: g.gate_id):
        n = int(g.gate_id.split("-")[1])
        if not _in_registry(n, GATE_RANGE):
            issues.append(
                f"gate {g.gate_id} outside the declared "
                f"G7-{GATE_RANGE[0]:02d}–G7-{GATE_RANGE[1]:02d} "
                f"registry ({g.spec}:{g.line})"
            )
    for sb in sorted(idx.scoreboard.values(), key=lambda s: s.sb_id):
        n = int(sb.sb_id.split("-")[1])
        if not _in_registry(n, SCOREBOARD_RANGE):
            issues.append(
                f"scoreboard {sb.sb_id} outside the declared "
                f"SB-{SCOREBOARD_RANGE[0]:02d}–SB-{SCOREBOARD_RANGE[1]:02d} "
                f"registry ({sb.spec}:{sb.line})"
            )
    for env in sorted(idx.envelopes.values(), key=lambda e: e.env_id):
        n = int(env.env_id[1])
        if not _in_registry(n, ENVELOPE_RANGE):
            issues.append(
                f"envelope {env.env_id} outside the declared "
                f"B{ENVELOPE_RANGE[0]}–B{ENVELOPE_RANGE[1]} "
                f"registry ({env.spec}:{env.line})"
            )
    for d in sorted(idx.defects.values(), key=lambda d: d.defect_id):
        n = int(d.defect_id.split("-")[1])
        if not _in_registry(n, DEFECT_RANGE):
            issues.append(
                f"defect {d.defect_id} outside the declared "
                f"D7-{DEFECT_RANGE[0]:02d}–D7-{DEFECT_RANGE[1]:02d} "
                f"registry ({d.spec}:{d.line})"
            )
    for st in sorted(idx.stages.values(), key=lambda s: s.stage_id):
        if st.stage_id not in STAGES:
            issues.append(
                f"stage {st.stage_id} is not a declared phase "
                f"({st.spec}:{st.line})"
            )

    # trace rows must name defined ids (Appendix B is a binding table)
    for t in idx.traces.values():
        for rid in t.requirements:
            if rid not in defined:
                issues.append(
                    f"trace {t.defect_id} names undefined requirement "
                    f"{rid} ({t.spec}:{t.line})"
                )
        for sc in t.scenarios:
            if sc not in idx.scenarios:
                issues.append(
                    f"trace {t.defect_id} names undefined scenario "
                    f"{sc} ({t.spec}:{t.line})"
                )
        if t.defect_id not in idx.defects:
            n = int(t.defect_id.split("-")[1])
            if _in_registry(n, DEFECT_RANGE):
                # reserved-but-undefined defect: allowed (audit wave)
                pass
    # register closed-by cells must name defined requirements
    for d in idx.defects.values():
        for rid in d.closed_by:
            if rid not in defined:
                issues.append(
                    f"defect {d.defect_id} closed-by names undefined "
                    f"requirement {rid} ({d.spec}:{d.line})"
                )

    # pinned spec hashes in the overlay must match the file on disk
    for fname, pinned in sorted(disp.spec_sha256.items()):
        actual = idx.spec_sha256.get(fname)
        if actual is None:
            issues.append(f"dispositions pin hash for unknown spec {fname}")
        elif pinned != actual:
            issues.append(
                f"stale spec hash for {fname}: dispositions pin "
                f"{pinned[:12]}..., file is {actual[:12]}... — run "
                f"`python -m eval.v7.ledger --write` after reviewing "
                f"the spec diff"
            )
    if not disp.missing:
        for fname in idx.spec_sha256:
            if fname not in disp.spec_sha256:
                issues.append(
                    f"dispositions do not pin a spec hash for {fname}"
                )

    inh_sc = idx.inherited_scenarios
    inh_gates = idx.inherited_gates
    for rid in sorted(set(disp.entries) - defined):
        issues.append(f"disposition row for unknown requirement {rid}")

    for rid, entry in sorted(disp.entries.items()):
        where = f"disposition {rid}"
        for key in sorted(set(entry) - DISPOSITION_KEYS):
            issues.append(f"{where}: unknown key {key!r}")
        for key in sorted(set(entry) & _DISPOSITION_LIST_KEYS):
            if not isinstance(entry[key], list) or not all(
                isinstance(v, str) and v for v in entry[key]
            ):
                issues.append(f"{where}: {key} must be a list of strings")
        for key in ("owner", "stage", "implementation_status",
                    "qualification_status", "blocker", "note"):
            if key in entry and not isinstance(entry[key], str):
                issues.append(f"{where}: {key} must be a string")

        impl = entry.get("implementation_status")
        qual = entry.get("qualification_status")
        if impl is not None and impl not in IMPLEMENTATION_STATUSES:
            issues.append(f"{where}: invalid implementation_status {impl!r}")
        if qual is not None and qual not in QUALIFICATION_STATUSES:
            issues.append(f"{where}: invalid qualification_status {qual!r}")
        stage = entry.get("stage")
        if stage and stage not in STAGES:
            issues.append(f"{where}: invalid stage {stage!r}")

        for ev in entry.get("evidence_type") or []:
            if ev not in EVIDENCE_LABELS:
                issues.append(f"{where}: invalid evidence label {ev!r}")
        executed = entry.get("executed_evidence") or []
        evidence_type = entry.get("evidence_type") or []
        if executed and not evidence_type:
            issues.append(
                f"{where}: executed_evidence requires evidence_type "
                f"labels (V7-00.06)"
            )
        if qual in ("locally_measured", "qualified") and not executed:
            issues.append(
                f"{where}: {qual!r} requires named executed evidence — "
                f"a citation or plan is not execution (V7-00.06)"
            )
        if qual == "qualified" and impl != "implemented":
            issues.append(
                f"{where}: 'qualified' requires implementation_status "
                f"'implemented'"
            )
        if qual == "failed" and not (
            entry.get("blocker") or entry.get("note")
        ):
            issues.append(
                f"{where}: 'failed' requires a blocker or note naming "
                f"cause/next verification (V7-00.06)"
            )
        if qual == "deferred" and not (
            (entry.get("owner") or "").strip()
            and (entry.get("blocker") or entry.get("note") or "").strip()
        ):
            issues.append(
                f"{where}: 'deferred' requires an owner and a reason "
                f"(V7-00.06, V6 F31 rule carried)"
            )

        for sc in entry.get("scenarios") or []:
            if not _is_scenario_id(sc):
                issues.append(f"{where}: invalid scenario id {sc!r}")
            elif sc.startswith("H") and sc not in idx.scenarios:
                issues.append(f"{where}: unknown scenario {sc}")
            elif sc[0] in "ECDF" and inh_sc and sc not in inh_sc:
                issues.append(f"{where}: unknown inherited scenario {sc}")
        for sb in entry.get("scoreboard") or []:
            if not re.match(r"^SB-\d{2}$", sb):
                issues.append(f"{where}: invalid scoreboard id {sb!r}")
            elif sb not in idx.scoreboard:
                issues.append(f"{where}: unknown scoreboard row {sb}")
        for g in entry.get("gate") or []:
            if not _is_gate_id(g):
                issues.append(f"{where}: invalid gate id {g!r}")
            elif g.startswith("G7") and g not in idx.gates:
                issues.append(f"{where}: unknown gate {g}")
            elif g.startswith(("G4", "G5", "G6")) and inh_gates and g not in inh_gates:
                issues.append(f"{where}: unknown inherited gate {g}")

        if root:
            for surf in entry.get("code_surfaces") or []:
                if not os.path.exists(os.path.join(root, surf)):
                    issues.append(
                        f"{where}: code surface {surf} does not exist — "
                        f"stale mapping (V7-00.06)"
                    )
    return issues


