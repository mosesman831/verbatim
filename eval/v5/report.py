"""Markdown report writer for the V5 harness (E70 / SPEC_V5 §24.10).

The report is generated from the executed-results dict — it renders
*what each suite measured, the real numbers, the misses, the
unavailable rows, and the unmeasured categories* in a fixed section
order so a reader can audit denominators and losses without digging
through JSON. Nothing is summarized away: a suite that failed to run
gets a FAILED row, a comparator that never executed gets an
UNAVAILABLE row, a metric with no support shows ``null``.
"""

from __future__ import annotations

import json
from typing import Any, Dict, List, Optional, Sequence

from . import stats as st


def _f(x: Any, digits: int = 3) -> str:
    if x is None:
        return "null"
    if isinstance(x, float):
        return f"{x:.{digits}f}"
    return str(x)


def _ms(row: Optional[dict]) -> str:
    if not row:
        return "n/a"
    return (f"p50={_f(row.get('p50'),1)} p95={_f(row.get('p95'),1)} "
            f"p99={_f(row.get('p99'),1)} n={row.get('n', 0)}")


def _status(s: Optional[str]) -> str:
    return (s or "unmeasured").upper()


def render_report(results: Dict[str, Any]) -> str:
    """Render the full V5 eval report as Markdown."""
    lines: List[str] = []
    rep = results
    lines.append("# V5 Evaluation Report")
    lines.append("")
    lines.append(f"Generated by `eval/v5/run.py` — "
                 f"qualification level: "
                 f"**{rep.get('qualification', 'locally_measured')}**")
    lines.append("")
    env = rep.get("environment") or {}
    if env:
        lines.append(
            f"Environment: python {env.get('python')}, sqlite "
            f"{env.get('sqlite')}, {env.get('platform')} "
            f"({env.get('machine')}), cpu={env.get('cpu_model', 'n/a')}, "
            f"cores={env.get('cpu_count_logical')}")
        lines.append("")

    suites = rep.get("suites") or {}
    # ---- overview table ---------------------------------------------
    lines.append("## Suite overview")
    lines.append("")
    lines.append("| suite | status | headline |")
    lines.append("|---|---|---|")
    for name, suite in suites.items():
        headline = _headline(name, suite)
        lines.append(f"| {name} | {_status(suite.get('verdict') or suite.get('status'))} "
                     f"| {headline} |")
    lines.append("")

    for name, suite in suites.items():
        lines.extend(_render_suite(name, suite))

    # ---- claims ledger ----------------------------------------------
    claims = rep.get("claims") or []
    if claims:
        lines.append("## Claim verdicts")
        lines.append("")
        lines.append("| claim | verdict | value | ci95 | reasons |")
        lines.append("|---|---|---|---|---|")
        for c in claims:
            lines.append(
                f"| {c.get('claim')} | {_status(c.get('verdict'))} | "
                f"{_f(c.get('value'),4)} | {_f(c.get('ci'))} | "
                f"{'; '.join(c.get('reasons') or []) or '—'} |")
        lines.append("")

    # ---- unmeasured / honesty ---------------------------------------
    unmeasured = rep.get("unmeasured") or []
    if unmeasured:
        lines.append("## Unmeasured categories")
        lines.append("")
        for u in unmeasured:
            lines.append(f"- {u}")
        lines.append("")
    rep_notes = rep.get("notes") or []
    if rep_notes:
        lines.append("## Notes")
        lines.append("")
        for n in rep_notes:
            lines.append(f"- {n}")
        lines.append("")
    return "\n".join(lines)


def _headline(name: str, suite: dict) -> str:
    if name == "quality":
        agg = suite.get("aggregate") or {}
        return (f"recall@k={_f(agg.get('recall_at_k'))} "
                f"abstain={_f((agg.get('abstain_correct') or {}).get('correct'))}/"
                f"{(agg.get('abstain_correct') or {}).get('n', 0)} "
                f"forbidden_hits={agg.get('forbidden_hits', 0)}")
    if name == "envelopes":
        a0 = suite.get("a0") or {}
        return (f"A0 search {_ms(a0.get('search_ms'))}; "
                f"misses={len(a0.get('misses') or [])}")
    if name == "frontier":
        pts = suite.get("points") or []
        acc = [p.get("accuracy") for p in pts if p.get("accuracy") is not None]
        return f"points={len(pts)} acc_range={_f(min(acc) if acc else None)}..{_f(max(acc) if acc else None)}"
    if name == "a3_probe":
        return f"scales={[p.get('memories') for p in suite.get('points') or []]} misses={len(suite.get('misses') or [])}"
    if name == "comparators":
        rows = suite.get("rows") or []
        return ", ".join(f"{r.get('name')}:{r.get('status')}" for r in rows)
    if name == "timers":
        t = (suite.get("stages_ms") or {}).get("total") or {}
        return f"search total {_ms(t)}"
    return _status(suite.get("verdict") or suite.get("status"))


def _render_suite(name: str, suite: dict) -> List[str]:
    out: List[str] = []
    out.append(f"## Suite: {name}")
    out.append("")
    out.append(f"- status: **{_status(suite.get('verdict') or suite.get('status'))}**")
    if suite.get("qualification"):
        out.append(f"- qualification: `{suite['qualification']}`")
    if suite.get("scale_disclosure"):
        out.append(f"- scale: {suite['scale_disclosure']}")
    if suite.get("corpus"):
        c = suite["corpus"]
        out.append(f"- corpus: {c.get('name')} items={c.get('items')} "
                   f"tasks={c.get('tasks')} digest={str(c.get('digest'))[:16]}…")
    if suite.get("error"):
        out.append(f"- **error**: `{suite['error']}`")

    if name == "quality":
        agg = suite.get("aggregate") or {}
        out.append(f"- recall@k: {_f(agg.get('recall_at_k'))}  "
                   f"precision@k: {_f(agg.get('precision_at_k'))}")
        ac = agg.get("abstain_correct") or {}
        out.append(f"- abstention: {ac.get('correct')}/{ac.get('n')} "
                   f"ci95={_f(ac.get('ci95'))}")
        out.append(f"- forbidden deliveries: {agg.get('forbidden_hits')} "
                   f"(unclean queries {agg.get('unclean_queries')})")
        for cat, row in sorted((suite.get("categories") or {}).items()):
            out.append(f"  - {cat}: n={row.get('n')} "
                       f"recall={_f(row.get('recall_mean'))} "
                       f"errors={row.get('errors')} "
                       f"forbidden={row.get('forbidden_hits')}")
        for p in suite.get("workflow_probes") or []:
            out.append(f"  - workflow: ready={p.get('ready_state')} "
                       f"found={p.get('search_found')} "
                       f"inspect={p.get('inspect_found')} "
                       f"forget={p.get('forget_completed')} "
                       f"post_forget_items={p.get('post_forget_items')}")
        for cl in suite.get("claims") or []:
            out.append(f"  - claim {cl.get('claim')}: "
                       f"{_status(cl.get('verdict'))} "
                       f"{'; '.join(cl.get('reasons') or [])}")
    elif name == "envelopes":
        for env_name in ("a0", "a1"):
            e = suite.get(env_name) or {}
            if not e:
                continue
            out.append(f"### {env_name.upper()} ({e.get('qualification')})")
            out.append(f"- scale: {json.dumps(e.get('scale') or {})}")
            out.append(f"- search: {_ms(e.get('search_ms'))}")
            out.append(f"- add ack: {_ms(e.get('add_ack_ms'))}")
            for m in e.get("misses") or []:
                out.append(f"- MISS: {m}")
            if e.get("backlog"):
                b = e["backlog"]
                out.append(f"- backlog: start={b.get('start')} "
                           f"peak={b.get('peak')} end={b.get('end')}")
    elif name == "frontier":
        out.append("| budget_tokens | accuracy | ci95 | mean_tokens | "
                   "tokens/correct | forbidden |")
        out.append("|---|---|---|---|---|---|")
        for p in suite.get("points") or []:
            out.append(
                f"| {p.get('budget_tokens')} | {_f(p.get('accuracy'))} | "
                f"{_f(p.get('ci95'))} | {_f(p.get('mean_delivered_tokens'))} | "
                f"{_f(p.get('tokens_per_correct'))} | "
                f"{p.get('forbidden_hits', 0)} |")
            if p.get("errors") and p.get("error_kinds"):
                out.append(
                    f"  - budget {p.get('budget_tokens')}: "
                    f"{p.get('errors')}/{p.get('tasks')} requests refused "
                    f"({'; '.join(p.get('error_kinds') or [])})")
        cp = suite.get("consumer_route_point") or {}
        out.append(f"| facade(natural) | {_f(cp.get('accuracy'))} | "
                   f"{_f(cp.get('ci95'))} | "
                   f"{_f(cp.get('mean_delivered_tokens'))} | "
                   f"{_f(cp.get('tokens_per_correct'))} | "
                   f"{cp.get('forbidden_hits', 0)} |")
        fc = suite.get("frontier_claim") or {}
        out.append(f"- frontier claim: {_status(fc.get('verdict'))} "
                   f"{'; '.join(fc.get('reasons') or [])}")
    elif name == "a3_probe":
        for p in suite.get("points") or []:
            out.append(f"### n={p.get('memories')}")
            out.append(f"- search: {_ms(p.get('search_ms'))}")
            out.append(f"- add ack: {_ms(p.get('add_ack_ms'))}")
            out.append(f"- lexical readiness: {_ms(p.get('lexical_readiness_ms'))}")
            out.append(f"- peak RSS: {_f(p.get('peak_rss_mib'),0)} MiB, "
                       f"drain cpu share: {_f(p.get('maintenance_cpu_share'))}, "
                       f"store: {_f(p.get('store_bytes'),0)} B")
        sc = suite.get("sublinear_check") or {}
        out.append(f"- sub-linear check: {_status(sc.get('verdict'))} "
                   f"alpha={_f(sc.get('alpha'))}")
        for m in suite.get("misses") or []:
            out.append(f"- MISS: {m}")
    elif name == "timers":
        for stage, row in sorted((suite.get("stages_ms") or {}).items()):
            out.append(f"  - {stage}: {_ms(row)}")
        b = suite.get("boundaries_ms") or {}
        for k, v in b.items():
            if isinstance(v, dict):
                out.append(f"  - boundary {k}: {_ms(v)}")
            else:
                out.append(f"  - boundary {k}: {v}")
        out.append(f"  - SQL/search: {_ms(suite.get('sql_per_search'))}")
    elif name == "comparators":
        out.append("| arm | status | accuracy | ci95 | reason |")
        out.append("|---|---|---|---|---|")
        for r in suite.get("rows") or []:
            m = r.get("metrics") or {}
            out.append(
                f"| {r.get('name')} | {r.get('status')} | "
                f"{_f(m.get('accuracy'))} | {_f(m.get('accuracy_ci95'))} | "
                f"{r.get('reason') or '—'} |")
        for cmp_ in suite.get("matrix") or []:
            out.append(f"  - compare {cmp_.get('a')} vs {cmp_.get('b')}: "
                       f"{'VALID ' + str(cmp_.get('winner')) if cmp_.get('valid') else 'REFUSED — ' + str(cmp_.get('reason'))}")
    else:
        # generic renderer for leakage/dx/consolidation/feedback
        if suite.get("checks"):
            for k, v in suite["checks"].items():
                out.append(f"  - {k}: {_status(v)}")
        if suite.get("probes"):
            for k, v in suite["probes"].items():
                out.append(f"  - {k}: {_status(v.get('verdict'))}")
        if suite.get("verdicts"):
            for k, v in suite["verdicts"].items():
                out.append(f"  - {k}: {_status(v)}")
        if suite.get("denominator"):
            d = suite["denominator"]
            out.append(f"  - steps ok: {d.get('ok')}/{d.get('attempted')}")
        if suite.get("steps"):
            for s in suite["steps"]:
                out.append(f"    - {s.get('name')}: {s.get('status')} "
                           f"{_f(s.get('ms'),1)}ms {s.get('error') or ''}")
    if suite.get("support"):
        sup = suite["support"]
        out.append(f"- support: executed={sup.get('tasks_executed', 'n/a')} "
                   f"errors={sup.get('errors', sup.get('read_error_count', 'n/a'))}")
    out.append("")
    return out


def write_report(results: Dict[str, Any], json_path: str,
                 md_path: str) -> None:
    """Write both artifacts — JSON (machine) + Markdown (human)."""
    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2, sort_keys=True, default=str)
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(render_report(results))


__all__ = ["render_report", "write_report"]
