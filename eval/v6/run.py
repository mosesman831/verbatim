"""CLI driver for the V6 eval portfolio.

Usage::

    python -m eval.v6.run                        # quick portfolio
    python -m eval.v6.run --full                 # larger local scale
    python -m eval.v6.run --suite comparators    # one suite (repeatable)
    python -m eval.v6.run --out-prefix /tmp/v6   # artifact location

Artifacts: ``<prefix>.json`` (full results), ``<prefix>.md`` (rendered
report), ``<prefix>.repro.json`` (reproduction manifest — built on the
V5 reproduction helper when importable, with a minimal local fallback).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from typing import Any, Dict, List, Optional, Sequence


# ---------------------------------------------------------------------------
# local report renderer (the v5 renderer is v5-suite-shaped; this one
# renders the v6 portfolio's comparators/tail surfaces)
# ---------------------------------------------------------------------------


def _f(x: Any, digits: int = 3) -> str:
    if x is None:
        return "null"
    if isinstance(x, float):
        return f"{x:.{digits}f}"
    return str(x)


def _status(s: Optional[str]) -> str:
    return (s or "unmeasured").upper()


def render_report(results: Dict[str, Any]) -> str:
    lines: List[str] = []
    lines.append("# V6 Evaluation Report")
    lines.append("")
    lines.append(
        f"Generated by `eval/v6/run.py` — qualification level: "
        f"**{results.get('qualification', 'locally_measured')}**")
    lines.append("")
    env = results.get("environment") or {}
    if env:
        lines.append(
            f"Environment: python {env.get('python')}, sqlite "
            f"{env.get('sqlite')}, {env.get('platform')} "
            f"({env.get('machine')}), cpu={env.get('cpu_model', 'n/a')}, "
            f"cores={env.get('cpu_count_logical')}")
        lines.append("")

    suites = results.get("suites") or {}
    lines.append("## Suite overview")
    lines.append("")
    lines.append("| suite | status | headline |")
    lines.append("|---|---|---|")
    for name, suite in suites.items():
        lines.append(
            f"| {name} | "
            f"{_status(suite.get('verdict') or suite.get('status'))} "
            f"| {_headline(name, suite)} |")
    lines.append("")

    for name, suite in suites.items():
        lines.extend(_render_suite(name, suite))

    unmeasured = results.get("unmeasured") or []
    if unmeasured:
        lines.append("## Unmeasured categories")
        lines.append("")
        for u in unmeasured:
            lines.append(f"- {u}")
        lines.append("")
    for n in results.get("notes") or []:
        lines.append(f"- {n}")
    return "\n".join(lines)


def _headline(name: str, suite: dict) -> str:
    if name == "comparators":
        rows = suite.get("rows") or []
        return ", ".join(
            f"{r.get('arm')}:{r.get('status')}" for r in rows)
    if name == "v5_tail":
        return (f"unresolved={suite.get('unresolved_count')}/"
                f"{suite.get('requirements_total')}")
    if name == "envelopes":
        envs = suite.get("envelopes") or {}
        return ", ".join(
            f"{k}:{(v.get('verdict') or v.get('status'))}"
            for k, v in envs.items())
    if name == "add_ack_scaling":
        cps = suite.get("checkpoints") or []
        sl = suite.get("superlinear_stages") or []
        return (f"checkpoints={[c.get('n') for c in cps]} "
                f"superlinear_stages={len(sl)}")
    if name == "twins":
        return (f"true {suite.get('auto_applied')}/"
                f"{suite.get('should_apply')}, false "
                f"{suite.get('false_applied')}/"
                f"{suite.get('false_total')}, bound95 "
                f"{suite.get('upper95_bound')}")
    if name == "neural":
        return f"neural_recommended={suite.get('neural_recommended')}"
    if suite.get("error"):
        return f"error: {suite['error'][:80]}"
    return _status(suite.get("verdict") or suite.get("status"))


def _render_suite(name: str, suite: dict) -> List[str]:
    out: List[str] = []
    out.append(f"## Suite: {name}")
    out.append("")
    out.append(
        f"- status: **{_status(suite.get('verdict') or suite.get('status'))}**")
    if suite.get("qualification"):
        out.append(f"- qualification: `{suite['qualification']}`")
    c = suite.get("corpus") or {}
    if c:
        out.append(
            f"- corpus: {c.get('name')} items={c.get('items')} "
            f"tasks={c.get('tasks')} digest={str(c.get('digest'))[:16]}…")
    if suite.get("error"):
        out.append(f"- **error**: `{suite['error']}`")

    if name == "comparators":
        out.append("")
        out.append("| arm | status | accuracy | recall@k | "
                   "precision@k | abstain | forbidden | p50 ms | "
                   "reason |")
        out.append("|---|---|---|---|---|---|---|---|---|")
        for r in suite.get("rows") or []:
            m = r.get("metrics") or {}
            ab = m.get("abstain") or {}
            lat = m.get("latency_ms") or {}
            out.append(
                f"| {r.get('arm')} | {r.get('status')} | "
                f"{_f(m.get('accuracy'))} | {_f(m.get('recall_at_k'))} | "
                f"{_f(m.get('precision_at_k'))} | "
                f"{ab.get('correct', '—')}/{ab.get('n', '—')} | "
                f"{m.get('forbidden_hits', '—')} | "
                f"{_f(lat.get('p50'), 1)} | "
                f"{(r.get('reason') or '—')[:80]} |")
        out.append("")
        out.append("### Pin coverage")
        out.append("")
        for r in suite.get("rows") or []:
            missing = r.get("pins_missing") or []
            out.append(
                f"- {r.get('arm')}: "
                + ("all 13 pins populated" if not missing
                   else f"missing {missing}"))
        out.append("")
        out.append("### Comparisons (verbatim_memory vs each arm)")
        out.append("")
        for cmp_ in suite.get("comparisons") or []:
            if cmp_.get("valid"):
                out.append(
                    f"- {cmp_.get('a')} vs {cmp_.get('b')}: VALID — "
                    f"winner={cmp_.get('winner')} "
                    f"delta={_f(cmp_.get('delta'), 4)}")
            else:
                out.append(
                    f"- {cmp_.get('a')} vs {cmp_.get('b')}: REFUSED — "
                    f"{cmp_.get('reason')}")
        out.append("")
        for r in suite.get("rows") or []:
            if r.get("notes"):
                out.append(f"#### notes: {r.get('arm')}")
                for n in r["notes"]:
                    out.append(f"- {n}")
                out.append("")
    elif name == "v5_tail":
        out.append(
            f"- dispositions: `{suite.get('dispositions_path')}`")
        out.append(
            f"- requirements total: {suite.get('requirements_total')}")
        for st_, n_ in (suite.get("status_counts") or {}).items():
            out.append(f"  - {st_}: {n_}")
        out.append(
            f"- **unresolved: {suite.get('unresolved_count')}**")
        ids = suite.get("unresolved_ids") or []
        if ids:
            out.append(f"  - ids ({len(ids)} shown): "
                       + ", ".join(ids[:40])
                       + (" …" if len(ids) > 40 else ""))
    elif name == "envelopes":
        envs = suite.get("envelopes") or {}
        out.append("")
        out.append("| envelope | verdict | search p50/p95/p99 ms | "
                   "add-ack p95 ms | misses |")
        out.append("|---|---|---|---|---|")
        for ename, e in envs.items():
            s = e.get("search_ms") or {}
            a = e.get("add_ack_ms") or {}
            out.append(
                f"| {ename} | "
                f"{_status(e.get('verdict') or e.get('status'))} | "
                f"{_f(s.get('p50'), 1)}/{_f(s.get('p95'), 1)}/"
                f"{_f(s.get('p99'), 1)} | {_f(a.get('p95'), 1)} | "
                f"{len(e.get('misses') or [])} |")
        out.append("")
        for ename, e in envs.items():
            out.append(f"### {ename}")
            sc = e.get("scale") or {}
            out.append(
                f"- scale: {sc.get('memories')} memories, "
                f"{sc.get('scale_disclosure') or 'declared scale'}")
            if e.get("budgets"):
                out.append(f"- budgets: `{json.dumps(e['budgets'], sort_keys=True)}`")
            for m in e.get("misses") or []:
                out.append(f"- MISS: {m}")
            for er in (e.get("errors") or [])[:4]:
                out.append(f"- error: {er}")
            vis = (e.get("measurements") or {}).get(
                "same_session_visibility")
            if vis:
                out.append(
                    f"- same-session visibility: "
                    f"{vis.get('satisfied_pct')} satisfied "
                    f"(observed={vis.get('observed')}, "
                    f"honest_pending={vis.get('honest_pending')}, "
                    f"unobserved_ready={vis.get('unobserved_ready')})")
            bl = e.get("backlog") or {}
            if bl:
                out.append(
                    f"- backlog: start={bl.get('start')} "
                    f"peak={bl.get('peak')} end={bl.get('end')} "
                    f"unbounded={bl.get('unbounded')}")
            out.append("")
    elif name == "add_ack_scaling":
        out.append(
            f"- scale_disclosure: {suite.get('scale_disclosure')}")
        out.append(
            f"- method: {(suite.get('stage_scaling') or {}).get('method')}")
        for c in suite.get("checkpoints") or []:
            a = c.get("add_ack_ms") or {}
            out.append(
                f"- n={c.get('n')}: add-ack p50={_f(a.get('p50'), 2)} "
                f"p95={_f(a.get('p95'), 2)} ms")
        for d in suite.get("superlinear_stages") or []:
            out.append(
                f"- SUPERLINEAR stage {d.get('stage')!r}: "
                f"alpha={d.get('alpha')} "
                f"({d.get('mean_first_ms')}ms → {d.get('mean_last_ms')}ms "
                f"over n={d.get('n_first')}→{d.get('n_last')})")
    elif name == "twins":
        out.append(
            f"- auto_applied: {suite.get('auto_applied')}/"
            f"{suite.get('should_apply')} true pairs")
        out.append(
            f"- false_applied: {suite.get('false_applied')}/"
            f"{suite.get('false_total')} false twins")
        out.append(
            f"- upper95_bound: {suite.get('upper95_bound')} "
            f"(target <{suite.get('bound_target')}, "
            f"bound_met={suite.get('bound_met')})")
        for p in suite.get("pairs") or []:
            if not p.get("ok"):
                out.append(
                    f"- PAIR MISS: {p.get('name')} "
                    f"({p.get('kind')}): applied={p.get('applied')} "
                    f"prior_disposition={p.get('prior_disposition')}")
    elif name == "neural":
        out.append(
            f"- neural_recommended: {suite.get('neural_recommended')}")
        out.append(f"- reason: {suite.get('gate_reason')}")
        d = suite.get("delta") or {}
        out.append(
            f"- delta recall@k: {_f(d.get('recall'), 4)}, "
            f"precision@k: {_f(d.get('precision'), 4)}")
        for arm_name, arm in (suite.get("arms") or {}).items():
            out.append(
                f"- {arm_name}: recall@k={_f(arm.get('recall_at_k'))} "
                f"precision@k={_f(arm.get('precision_at_k'))} "
                f"tasks={arm.get('tasks')} errors={arm.get('errors')}")
    else:
        for k, v in suite.items():
            if k in ("suite", "status", "verdict", "qualification",
                     "corpus", "error", "traceback"):
                continue
            if isinstance(v, (str, int, float, bool)) or v is None:
                out.append(f"- {k}: {_f(v)}")
    out.append("")
    return out


def write_report(results: Dict[str, Any], json_path: str,
                 md_path: str) -> None:
    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2, sort_keys=True, default=str)
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(render_report(results))


# ---------------------------------------------------------------------------
# reproduction manifest — V5 helper when importable, minimal fallback
# ---------------------------------------------------------------------------


def write_manifest(results: Dict[str, Any], path: str, *,
                   command: str,
                   artifact_paths: Sequence = ()) -> Dict[str, Any]:
    try:
        from eval.v5.reproduction import build_manifest
        m = build_manifest(
            results, command=command, artifact_paths=artifact_paths)
        m["manifest_version"] = "v6-repro-1"
        m["portfolio"] = "v6"
    except Exception:  # noqa: BLE001 — minimal honest fallback
        from eval.v5.harness import environment
        artifacts = {}
        for p in artifact_paths or ():
            try:
                with open(p, "rb") as fh:
                    artifacts[os.path.basename(p)] = hashlib.sha256(
                        fh.read()).hexdigest()
            except OSError:
                artifacts[os.path.basename(p)] = "unreadable"
        m = {
            "manifest_version": "v6-repro-1",
            "portfolio": "v6",
            "command": command,
            "seed": results.get("seed"),
            "environment": environment(),
            "artifact_sha256": artifacts,
            "qualification": results.get("qualification"),
        }
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(m, fh, indent=2, sort_keys=True, default=str)
    return m


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main(argv: Optional[Sequence[str]] = None) -> int:
    p = argparse.ArgumentParser(prog="eval.v6.run")
    p.add_argument("--full", action="store_true",
                   help="larger local scale (still locally measured)")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--suite", action="append",
                   help="restrict to named suite(s); repeatable")
    p.add_argument("--out-prefix", default="eval/v6/report_v6",
                   help="artifact path prefix")
    p.add_argument("--workdir", default=None,
                   help="shared workdir (default: per-suite tempdirs)")
    args = p.parse_args(argv)

    from .portfolio import run_portfolio

    results = run_portfolio(
        quick=not args.full, seed=args.seed,
        suites=args.suite, workdir=args.workdir)

    out = args.out_prefix
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    json_path = out + ".json"
    md_path = out + ".md"
    write_report(results, json_path, md_path)
    write_manifest(
        results, out + ".repro.json",
        command="python -m eval.v6.run " + " ".join(sys.argv[1:]),
        artifact_paths=(json_path, md_path))

    verdict = results.get("verdict", "unknown")
    print(f"[v6] suites: {list((results.get('suites') or {}).keys())}")
    print(f"[v6] verdict: {verdict} "
          f"(qualification={results.get('qualification')})")
    for name, suite in (results.get("suites") or {}).items():
        st = suite.get("verdict") or suite.get("status")
        print(f"  {name}: {st}")
    comp = (results.get("suites") or {}).get("comparators") or {}
    for r in comp.get("rows") or []:
        m = r.get("metrics") or {}
        print(f"    arm {r.get('arm')}: {r.get('status')} "
              f"accuracy={m.get('accuracy')} "
              f"recall@k={m.get('recall_at_k')} "
              f"reason={r.get('reason') or '—'}")
    print(f"[v6] wrote {json_path}, {md_path}, {out + '.repro.json'}")
    return 0 if verdict in ("passed", "inconclusive", "failed") else 1


if __name__ == "__main__":
    raise SystemExit(main())
